const CATALOG = {
  en: EN,
  fr: FR,
  es: ES,
  it: IT,
  pt: PT,
  de: DE,
};

let activeLocale = 'en';

/**
 * @param {string} [code] BCP-47-ish tag or bare code: en, fr, de, … "pr" → pt (common typo).
 */
export function normalizeLocale(code) {
  if (code == null || code === '') return 'en';
  let c = String(code).trim().toLowerCase();
  if (c === 'pr') c = 'pt';
  const base = c.split(/[-_]/u)[0] || 'en';
  if (Object.prototype.hasOwnProperty.call(CATALOG, base)) return base;
  return 'en';
}

export function setLocale(code) {
  activeLocale = normalizeLocale(code);
}

export function getLocale() {
  return activeLocale;
}

/**
 * @param {string} key
 * @param {Record<string, string | number>} [vars] `{ name: 'x' }` → replaces `{name}` in the string
 */
export function t(key, vars) {
  const table = CATALOG[activeLocale] || EN;
  const fallback = EN;
  let s = (table[key] ?? fallback[key] ?? key);
  if (typeof s !== 'string') return String(s);
  if (vars && typeof s === 'string') {
    s = s.replace(/\{(\w+)\}/g, (_, k) =>
      (vars[k] != null ? String(vars[k]) : `{${k}}`));
  }
  return s;
}

/** @returns {{ id: string, name: string, prompt: string, icon: string }[]} */
export function getDefaultQuickActions() {
  const table = CATALOG[activeLocale] || EN;
  const raw = table.defaults || EN.defaults;
  return raw.map((a, i) => ({
    id: String(i + 1),
    name: a.name,
    prompt: a.prompt,
    icon: a.icon,
  }));
}

