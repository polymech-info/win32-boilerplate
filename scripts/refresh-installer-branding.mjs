/**
 * Regenerates dist/installer/branding.nsh from cmake/Branding.cmake, package.json,
 * and optional dist/branding/pm_image.ico (same as src/win/ui_next/Resource.rc IDW_MAIN).
 * Run: node scripts/refresh-installer-branding.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')

const PRODUCT_WEB_SITE =
  'https://service.polymech.info/user/cgo/pages/polymech-media-tools'

const cmake = fs.readFileSync(path.join(root, 'cmake/Branding.cmake'), 'utf8')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))

/**
 * @param {string} name
 */
function setVal(name) {
  const re = new RegExp('^set\\(' + name + '\\s+\"([^\"]*)\"\\s*\\)\\s*$', 'm')
  const m = re.exec(cmake)
  if (!m) {
    throw new Error(`Branding.cmake: need set(${name} "literal") (no \${} refs)`)
  }
  return m[1]
}

const PM_BRAND_VENDOR = setVal('PM_BRAND_VENDOR')
const PM_BRAND_APP_DISPLAY = setVal('PM_BRAND_APP_DISPLAY')
const PM_BRAND_APP_DESCRIPTION = setVal('PM_BRAND_APP_DESCRIPTION')
const PM_APP_ID_SLUG = setVal('PM_APP_ID_SLUG')
const PM_IEXECUTE_BASENAME = setVal('PM_IEXECUTE_BASENAME')
const uninstKeyInner =
  'Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\$' + '{PRODUCT_NAME}'

const ico = path.join(root, 'dist', 'branding', 'pm_image.ico')
const icoNsis = 'dist\\branding\\pm_image.ico'
const useAppIco = fs.existsSync(ico)
const muiIcon = useAppIco
  ? `!define MUI_ICON "${icoNsis}"`
  : '!define MUI_ICON "${NSISDIR}\\Contrib\\Graphics\\Icons\\modern-install.ico"'
const muiUnicon = useAppIco
  ? `!define MUI_UNICON "${icoNsis}"`
  : '!define MUI_UNICON "${NSISDIR}\\Contrib\\Graphics\\Icons\\modern-uninstall.ico"'

const lines = [
  '; === Generated by scripts/refresh-installer-branding.mjs — do not hand-edit. ===',
  `!define PM_BRAND_VENDOR "${esc(PM_BRAND_VENDOR)}"`,
  `!define PM_BRAND_APP_DISPLAY "${esc(PM_BRAND_APP_DISPLAY)}"`,
  `!define PM_BRAND_APP_DESCRIPTION "${esc(PM_BRAND_APP_DESCRIPTION)}"`,
  `!define PM_APP_ID_SLUG "${esc(PM_APP_ID_SLUG)}"`,
  `!define PM_IEXECUTE_BASENAME "${esc(PM_IEXECUTE_BASENAME)}"`,
  `!define PM_IEXECUTE_DLL "${esc(PM_IEXECUTE_BASENAME)}.dll"`,
  `!define PRODUCT_VERSION "${esc(String(pkg.version))}"`,
  `!define PRODUCT_NAME "${esc(PM_BRAND_APP_DESCRIPTION)}"`,
  `!define PRODUCT_PUBLISHER "${esc(PM_BRAND_VENDOR)}"`,
  `!define PRODUCT_WEB_SITE "${esc(PRODUCT_WEB_SITE)}"`,
  `!define PRODUCT_EXE "${esc(PM_APP_ID_SLUG + '.exe')}"`,
  `!define PRODUCT_APPDATA_SUBDIR "${esc(PM_BRAND_VENDOR + '\\' + PM_APP_ID_SLUG)}"`,
  `!define STARTMENU_FOLDER "${esc(PM_BRAND_APP_DISPLAY)}"`,
  `!define PRODUCT_UNINST_KEY "${uninstKeyInner}"`,
  '!define ENV_KEY "Environment"',
  '',
  `!define MUI_WELCOMEPAGE_TITLE "Welcome to ${esc(PM_BRAND_APP_DISPLAY)} setup"`,
  `!define MUI_WELCOMETEXT "This will install ${esc(
    PM_BRAND_APP_DISPLAY,
  )} (${esc(PM_BRAND_APP_DESCRIPTION)}). It includes ${esc(
    PM_IEXECUTE_BASENAME,
  )}.dll for the Explorer IExecute extension. At the end of the wizard, context menus and Open With are registered for your user account."`,
  '!define MUI_FINISHTITLE "Complete"',
  `!define MUI_FINISHTEXT "You can start ${esc(
    PM_BRAND_APP_DISPLAY,
  )} from the Start Menu, or from Explorer after registration completes."`,
  '!define MUI_ABORTWARNING',
  muiIcon,
  muiUnicon,
  '',
]
fs.mkdirSync(path.join(root, 'dist', 'installer'), { recursive: true })
const outNsh = path.join(root, 'dist', 'installer', 'branding.nsh')
fs.writeFileSync(outNsh, lines.join('\r\n') + '\r\n', 'utf8')
if (!useAppIco) {
  process.stderr.write(
    '[install branding] dist/branding/pm_image.ico not found; using NSIS stock install/uninstall icons. ' +
      'Add dist/branding/pm_image.ico to match the application icon.\n',
  )
} else {
  process.stderr.write(`[install branding] MUI uses ${icoNsis}\n`)
}
process.stdout.write('Wrote ' + outNsh + '\n')

/**
 * @param {string} s
 */
function esc(s) {
  return s
    .replaceAll('\\', '\\\\')
    .replaceAll('\r', '')
    .replaceAll('\n', '\\n')
    .replaceAll('\t', '\\t')
    .replaceAll('"', '$\\"')
}
